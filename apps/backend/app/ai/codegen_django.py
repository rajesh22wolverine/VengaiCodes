# ═══════════════════════════════════════════════════════════════
#  VengaiCode — Deterministic (no-AI) Django + Django REST Framework
#  ai/codegen_django.py — The Django backend codegen_deterministic
#  dispatches to. Everything is written from the db_schema SNAPSHOT
#  (via django_render), the same data the migrations are rendered from,
#  so the models and api/migrations/ always agree.
#
#  What the screens get is the same REST surface as every other
#  backend: GET/POST /api/<table>, GET/PUT/DELETE /api/<table>/<id>
#  (no trailing slash; PUT changes only the fields it sends), JSON with
#  the column names as keys, the database's constraint violations as
#  readable {"detail": ...} messages (409 duplicate, 422 broken rule),
#  and a refused delete as 409. Field validation is DRF's own
#  (400, {"field": ["message"]}), which the screens also read.
# ═══════════════════════════════════════════════════════════════

