#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════
//  VengaiCode Mobile — Design Studio asset generator
//  Reads grapesjs/grapesjs-blocks-basic's minified dist files and
//  writes them out as JSON.stringify-escaped string constants, so
//  Design Studio's WebView document (designStudioDocument.ts) can
//  inline them without any Metro asset-bundling config (this repo
//  has none for .html/.js/.css — see the Design Studio mobile plan).
//
//  Re-run this after upgrading grapesjs / grapesjs-blocks-basic:
//    node scripts/generate-design-studio-assets.mjs
// ═══════════════════════════════════════════════════════════════

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));

const GRAPESJS_JS_PATH = require.resolve("grapesjs/dist/grapes.min.js");
const GRAPESJS_CSS_PATH = join(dirname(GRAPESJS_JS_PATH), "css", "grapes.min.css");
const GJS_BLOCKS_BASIC_JS_PATH = require.resolve("grapesjs-blocks-basic/dist/index.js");

const grapesjsJs = readFileSync(GRAPESJS_JS_PATH, "utf8");
const grapesjsCss = readFileSync(GRAPESJS_CSS_PATH, "utf8");
const gjsBlocksBasicJs = readFileSync(GJS_BLOCKS_BASIC_JS_PATH, "utf8");

const output = `// ═══════════════════════════════════════════════════════════════
//  AUTO-GENERATED by scripts/generate-design-studio-assets.mjs
//  Do not edit by hand — re-run the script instead.
// ═══════════════════════════════════════════════════════════════

export const GRAPESJS_JS = ${JSON.stringify(grapesjsJs)};

export const GRAPESJS_CSS = ${JSON.stringify(grapesjsCss)};

export const GJS_BLOCKS_BASIC_JS = ${JSON.stringify(gjsBlocksBasicJs)};
`;

const outPath = join(__dirname, "..", "src", "lib", "designStudioAssets.generated.ts");
writeFileSync(outPath, output, "utf8");

console.log(`Wrote ${outPath}`);
console.log(`  grapesjs.js: ${(grapesjsJs.length / 1024).toFixed(0)} KB`);
console.log(`  grapesjs.css: ${(grapesjsCss.length / 1024).toFixed(0)} KB`);
console.log(`  grapesjs-blocks-basic.js: ${(gjsBlocksBasicJs.length / 1024).toFixed(0)} KB`);
